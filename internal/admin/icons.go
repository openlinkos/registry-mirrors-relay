package admin

import (
	"bytes"
	"html/template"
	"regexp"
	"slices"
	"strings"
)

// iconNames are the Lucide icons the console uses, all from the design system's icon set
// (assets/vendor/icons.json); loading checks that each one is there.
var iconNames = []string{
	"activity", "arrow-left", "ban", "check", "circle-alert", "circle-check", "clock", "copy", "cpu", "database",
	"download", "external-link", "filter", "globe", "hard-drive", "info", "key-round", "languages", "layout-dashboard",
	"list", "lock", "log-in", "log-out", "menu", "moon", "pencil", "plug", "plus", "refresh-cw", "scroll-text",
	"rotate-ccw", "search", "server", "settings", "shield-check", "sun", "sun-moon", "terminal", "trash-2", "triangle-alert",
	"user", "wrench", "x",
}

var iconNameRe = regexp.MustCompile(`^[a-z0-9-]+$`)

// iconPrefix keeps symbol ids from clashing with other ids on the page.
const iconPrefix = "i-"

// icon draws an icon that refers to a symbol carried by the page:
// <svg class="ol-icon"><use href="#i-search"/></svg>. Once the page is rendered, symbols are generated
// for the names it refers to (see withSprite), so each page carries only the icons it uses.
func icon(name string, size ...string) template.HTML {
	if !slices.Contains(iconNames, name) {
		panic("unregistered icon " + name) // a development error; the tests cover every page
	}
	cls := "ol-icon"
	if len(size) > 0 && (size[0] == "sm" || size[0] == "lg") {
		cls += " ol-icon-" + size[0]
	}
	return template.HTML(`<svg class="` + cls + `" aria-hidden="true"><use href="#` + iconPrefix + name + `"/></svg>`) //nolint:gosec // the name comes from the allowlist above
}

// spriteMark is the place in the layout for the icon symbols; it is replaced after rendering.
const spriteMark = `<svg data-sprite hidden></svg>`

var iconRef = regexp.MustCompile(`<use href="#` + iconPrefix + `([a-z0-9-]+)"/>`)

// withSprite puts the symbols of the icons the page refers to in place of spriteMark. Values in the text
// are all escaped and never appear in this quoted form, so only the markup generated by icon() matches.
func (a *assets) withSprite(page []byte) []byte {
	seen := map[string]bool{}
	for _, m := range iconRef.FindAllSubmatch(page, -1) {
		seen[string(m[1])] = true
	}
	var b strings.Builder
	if len(seen) > 0 {
		names := make([]string, 0, len(seen))
		for n := range seen {
			names = append(names, n)
		}
		slices.Sort(names)
		b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" hidden aria-hidden="true">`)
		for _, n := range names {
			b.WriteString(`<symbol id="` + iconPrefix + n + `" viewBox="` + template.HTMLEscapeString(a.viewBox) + `">`)
			b.WriteString(a.icons[n]) // checked at load time to be basic shapes only
			b.WriteString(`</symbol>`)
		}
		b.WriteString(`</svg>`)
	}
	return bytes.Replace(page, []byte(spriteMark), []byte(b.String()), 1)
}
